                                <p>Much of this criticism is not lost on Dweck, and she deserves great credit for
                                    responding to it and adapting her work accordingly. In fact, she argues that her
                                    work has been misunderstood and misapplied in a range of ways. She has also
                                    expressed concerns that her theories are being misappropriated in schools by being
                                    conflated with the self-esteem movement: ‘For me the growth mindset is a tool for
                                    learning and improvement. It’s not just a vehicle for making children feel good.’
                                </p>
                                <p>But there is another factor at work here. The failure to translate the growth mindset
                                    into the classroom might reflect a misunderstanding of the nature of teaching and
                                    learning itself. Growth mindset supporters David Yeager and Gregory Walton claim
                                    that interventions should be delivered in a subtle way to maximise their
                                    effectiveness. They say that if adolescents perceive a teacher’s intervention as
                                    conveying that they are in need of help, this could undo its intended effects.</p>
                                <p>A lot of what drives students is their innate beliefs and how they perceive
                                    themselves. There is a strong correlation between self-perception and achievement,
                                    but there is evidence to suggest that the actual effect of achievement on
                                    self-perception is stronger than the other way round. To stand up in a classroom and
                                    successfully deliver a good speech is a genuine achievement, and that is likely to
                                    be more powerfully motivating than vague notions of ‘motivation’ itself.</p>
                                <p>Recent evidence would suggest that growth mindset interventions are not the elixir of
                                    student learning that its proponents claim it to be. The growth mindset appears to
                                    be a viable construct in the lab, which, when administered in the classroom via
                                    targeted interventions, doesn’t seem to work. It is hard to dispute that having
                                    faith in the capacity to change is a good attribute for students. Paradoxically,
                                    however, that aspiration is not well served by direct interventions that try to
                                    instil it.</p>
                                <p>Motivational posters and talks are often a waste of time, and might well give
                                    students a deluded notion of what success actually means. Teaching concrete skills
                                    such as how to write an effective introduction to an essay then praising students’
                                    effort in getting there is probably a far better way of improving confidence than
                                    telling them how unique they are, or indeed how capable they are of changing their
                                    own brains. Perhaps growth mindset works best as a philosophy and not an
                                    intervention.</p>
