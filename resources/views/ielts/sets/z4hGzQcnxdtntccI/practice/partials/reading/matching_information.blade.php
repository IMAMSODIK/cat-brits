                    <h3 class="passage-title">B</h3>
                    <p>Ongoing research is showcasing how green roofs in cities can integrate with ‘living
                        walls’: environmentally friendly walls which are partially or completely covered
                        with greenery, including a growing medium, such as soil or water. Research also
                        indicates that green roofs can be integrated with drainage systems on the ground,
                        such as street trees, so that the water is managed better and the built environment
                        is made more sustainable. There is also evidence to demonstrate the social value of
                        green roofs. Doctors are increasingly prescribing time spent gardening outdoors for
                        patients dealing with anxiety and depression. And research has found that access to
                        even the most basic green spaces can provide a better quality of life for dementia
                        sufferers and help people avoid obesity.</p>
                    <h3 class="passage-title">C</h3>
                    <p>For green roofs to become the norm for new developments, there needs to be support
                        from public authorities and private investors. Those responsible for maintaining
                        buildings may have to acquire new skills, such as landscaping, and in some cases,
                        volunteers may be needed to help out. Other considerations include installing
                        drainage paths, meeting health and safety requirements and perhaps allowing access
                        for the public, as well as planning restrictions and disruption from regular
                        activities in and around the buildings during installation. To convince investors
                        and developers that installing green roofs is worthwhile, economic arguments are
                        still the most important. The term ‘natural capital’ has been developed to explain
                        the economic value of nature; for example, measuring the money saved by installing
                        natural solutions to protect against flood damage, adapt to climate change or help
                        people lead healthier and happier lives.</p>
                    <h3 class="passage-title">D</h3>
                    <p>High achievers have been found to use self-regulatory learning strategies more often
                        and more effectively than lower achievers, and are better able to transfer these
                        strategies to deal with unfamiliar tasks. This happens to such a high degree in some
                        children that they appear to be demonstrating talent in particular areas.
                        Overviewing research on the thinking process of highly able children, (Shore and
                        Kanevsky, 1993) put the instructor’s problem succinctly: ‘If they [the gifted]
                        merely think more quickly, then .we need only teach more quickly. If they merely
                        make fewer errors, then we can shorten the practice’. But of course, this is not
                        entirely the case; adjustments have to be made in methods of learning and teaching,
                        to take account of the many ways individuals think.</p>
                    <h3 class="passage-title">E</h3>
                    <p>As the expertise about green roofs grows, official standards have been developed to
                        ensure that they are designed, constructed and maintained properly, and function
                        well. Improvements in the science and technology underpinning green roof development
                        have also led to new variations in the concept. For example, ‘blue roofs’ enable
                        buildings to hold water over longer periods of time, rather than draining it away
                        quickly – crucial in times of heavier rainfall. There are also combinations of green
                        roofs with solar panels, and ‘brown roofs’ which are wilder in nature and maximise
                        biodiversity. If the trend continues, it could create new jobs and a more vibrant
                        and sustainable local food economy – alongside many other benefits. There are still
                        barriers to overcome, but the evidence so far indicates that green roofs have the
                        potential to transform cities and help them function sustainably long into the
                        future. The success stories need to be studied and replicated elsewhere, to make
                        green, blue, brown and food-producing roofs the norm in cities around the world.</p>
