            <div class="passage-body">
                <p>
                    Let us start by looking at a modern ‘genius’, Maryam Mirzakhani, who died at the early age of 40.
                    She was the only woman to win the Fields Medal, the mathematical equivalent of a Nobel prize. It
                    would be easy to assume that someone as special as Mirzakhani must have been one of those ‘gifted’
                    children, those who have an extraordinary ability in a specific sphere of activity or knowledge. But
                    look closer and a different story emerges. Mirzakhani was born in Tehran, Iran. She went to a highly
                    selective girls’ school but maths wasn’t her interest – reading was. She loved novels and would read
                    anything she could lay her hands on. As for maths, she did rather poorly at it for the first couple
                    of years in her middle school, but became interested when her elder brother told her about what he’d
                    learned. He shared a famous maths problem from a magazine that fascinated her and she was hooked.
                </p>

                <p>
                    In adult life it is clear that she was curious, excited by what she did and also resolute in the
                    face of setbacks. One of her comments sums it up. ‘Of course, the most rewarding part is the “Alia”
                    moment, the excitement of discovery and enjoyment of understanding something new … But most of the
                    time, doing mathematics for me is like being on a long hike with no trail and no end in sight.’ That
                    trail took her to the heights of original research into mathematics.
                </p>
