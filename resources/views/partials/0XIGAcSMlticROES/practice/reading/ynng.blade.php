            <h3 class="passage-title">An inquiry into the existence of the gifted child</h3>
            <div class="passage-body">
                <p>
                    Is her background unusual? Apparently not. Most Nobel prize winners were unexceptional in childhood.
                    Einstein was slow to talk as a baby. He failed the general part of the entry test to Zurich
                    Polytechnic –
                    though they let him in because of high physics and maths scores. He struggled at work initially, but
                    he
                    kept plugging away and eventually rewrote the laws of Newtonian mechanics with his theory of
                    relativity.
                </p>

                <p>
                    There has been a considerable amount of research on high performance over the last century that
                    suggests
                    it goes way beyond tested intelligence. On top of that, research is clear that brains are flexible,
                    new
                    neural pathways can be created, and IQ isn’t fixed. For example, just because you can read stories
                    with
                    hundreds of pages at the age of five doesn’t mean you will still be ahead of your contemporaries in
                    your
                    teens. While the jury is out on giftedness being innate and other factors potentially making the
                    difference,
                    what is certain is that the behaviours associated with high levels of performance are replicable and
                    most
                    can be taught even traits such as curiosity.
                </p>

                <p>
                    According to my colleague Prof Deborah Eyre, with whom I’ve collaborated on the book <i>Great Minds
                        and How to Crow Them</i>,
                    the latest neuroscience and psychological research suggests most individuals can reach levels of
                    performance
                    associated in school with the gifted and talented. However, they must be taught the right attitudes
                    and
                    approaches to their learning and develop the attributes of high performers—curiosity, persistence
                    and hard
                    work, for example an approach Eyre calls ‘high performance learning’. Critically, they need the
                    right support
                    in developing those approaches at home as well as at school.
                </p>

                <p>
                    Prof Anders Ericsson, an eminent education psychologist at Florida State University, US, is the
                    co-author of
                    <i>Peak: Secrets from the New Science of Expertise</i>. After research going back to 1980 into
                    diverse achievements,
                    from music to memory to sport, he doesn’t think unique and innate talents are at the heart of
                    performance.
                    Deliberate practice, that stretches you every step of the way, and around 10,000 hours of it, is
                    what produces
                    the goods. It’s not a magic number—the highest performers move on to doing a whole lot more, of
                    course.
                    Ericsson’s memory research is particularly interesting because random students, trained in memory
                    techniques
                    for the study, went on to outperform others thought to have innately superior memories—those who you
                    might
                    call gifted.
                </p>

                <p>
                    But it is perhaps the work of Benjamin Bloom, another distinguished American educationist working in
                    the 1980s,
                    that gives the most pause for thought. Bloom’s team looked at a group of extraordinarily high
                    achieving people
                    in disciplines as varied as ballet, swimming, piano, tennis, maths, sculpture and neurology. He
                    found a pattern
                    of parents encouraging and supporting their children, often in areas they enjoyed themselves.
                    Bloom’s outstanding
                    people had worked very hard and consistently at something they had become hooked on when at a young
                    age, and
                    their parents all emerged as having strong work ethics themselves.
                </p>

                <p>
                    Eyre says we know how high performers learn. From that she has developed a high performing learning
                    approach.
                    She is working on this with a group of schools, both in Britain and abroad. Some spin-off research,
                    which looked
                    in detail at 24 of the 3,000 children being studied who were succeeding despite difficult
                    circumstances, found
                    something remarkable. Half were getting free school meals because of poverty, more than half were
                    living with a
                    single parent, and four in five were living in disadvantaged areas. Interviews uncovered strong
                    evidence of an
                    adult or adults in the child’s life who valued and supported education, either in the immediate or
                    extended
                    family or in the child’s wider community. Children talked about the need to work hard at school, to
                    listen in
                    class and keep trying. Let us end with Einstein, the epitome of a genius. He clearly had curiosity,
                    character
                    and determination. He struggled against rejection in early life but was undeterred. Did he think he
                    was a genius
                    or even gifted? He once wrote: ‘It’s not that I’m so smart, it’s just that I stay with problems
                    longer. Most
                    people say it is the intellect which makes a great scientist. They are wrong: it is character.’
                </p>
            </div>

