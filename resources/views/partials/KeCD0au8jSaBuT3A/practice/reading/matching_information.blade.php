                <h3>Forest management in Pennsylvania, USA</h3>
                <p><i>How managing low-quality wood (also known as low-use wood) for bioenergy can encourage sustainable
                        forest management</i></p>

                <h3>A</h3>
                <p>A tree’s ‘value’ depends on several factors including its species, size, form, condition, quality,
                    function, and accessibility, and depends on the management goals for a given forest. The same tree
                    can be valued very differently by each person who looks at it. A large, straight black cherry tree
                    has high value as timber to be cut into logs or made into furniture, but for a landowner more
                    interested in wildlife habitat, the real value of that stem (or trunk) may be the food it provides
                    to animals. Likewise, if the tree suffers from black knot disease, its value for timber decreases,
                    but to a woodworker interested in making bowls, it brings an opportunity for a unique and beautiful
                    piece of art.</p>

                <h3>B</h3>
                <p>In the past, Pennsylvania landowners were solely interested in the value of their trees as
                    high-quality timber. The norm was to remove the stems of highest quality and leave behind poorly
                    formed trees that were not as well suited to the site where they grew. This practice, called
                    ‘high-grading’, has left a legacy of ‘low-use wood’ in the forests. Some people even call these
                    ‘junk trees’, and they are abundant in Pennsylvania. These trees have lower economic value for
                    traditional timber markets, compete for growth with higher-value trees, shade out desirable
                    regeneration and decrease the health of a stand leaving it more vulnerable to poor weather and
                    disease. Management that specifically targets low-use wood can help landowners manage these forest
                    health issues, and wood energy markets help promote this.</p>

                <h3>C</h3>
                <p>Wood energy markets can accept less expensive wood material of lower quality than would be suitable
                    for traditional timber markets. Most wood used for energy in Pennsylvania is used to produce heat or
                    electricity through combustion. Many schools and hospitals use wood boiler systems to heat and power
                    their facilities, many homes are primarily heated with wood, and some coal plants incorporate wood
                    into their coal streams to produce electricity. Wood can also be gasified for electrical generation
                    and can even be made into liquid fuels like ethanol and gasoline for lorries and cars. All these
                    products are made primarily from low-use wood. Several tree- and plant-cutting approaches, which
                    could greatly improve the long-term quality of a forest, focus strongly or solely on the use of wood
                    for those markets.</p>

                <h3>D</h3>
                <p>One such approach is called a Timber Stand Improvement (TSI) Cut. In a TSI Cut, really poor-quality
                    tree and plant material is cut down to allow more space, light, and other resources to the
                    highest-valued stems that remain. Removing invasive plants might be another primary goal of a TSI
                    Cut. The stems that are left behind might then grow in size and develop more foliage and larger
                    crowns or tops that produce more coverage for wildlife; they have a better chance to regenerate in a
                    less crowded environment. TSI Cuts can be tailored to one farmer’s specific management goals for his
                    or her land.</p>

                <h3>E</h3>
                <p>Another approach that might yield a high amount of low-use wood is a Salvage Cut. With the many pests
                    and pathogens visiting forests including hemlock wooly adelgid, Asian longhomed beetle, emerald ash
                    borer, and gypsy moth, to name just a few, it is important to remember that those working in the
                    forests can help ease these issues through cutting procedures. These types of cut reduce the number
                    of sick trees and seek to manage the future spread of a pest problem. They leave vigorous trees that
                    have stayed healthy enough to survive the outbreak.</p>
