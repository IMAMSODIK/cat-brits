                <h3>B</h3>
                <p>
                    Concern about space junk goes back to the beginning of the satellite era, but the number of objects
                    in orbit is rising so rapidly that researchers are investigating new ways of attacking the problem.
                    Several teams are trying to improve methods for assessing what is in orbit, so that satellite
                    operators can work more efficiently in ever-more-crowded space. Some researchers are now starting
                    to compile a massive data set that includes the best possible information on where everything is in
                    orbit. Others are developing taxonomies of space – working on measuring properties such as the shape
                    and size of an object, so that satellite operators know how much to worry about what’s coming their
                    way.
                </p>
                <p>
                    The alternative, many say, is unthinkable. Just a few uncontrolled space crashes could generate
                    enough debris to set off a runaway cascade of fragments, rendering near-Earth space unusable. ‘If we
                    go on like this, we will reach a point of no return,’ says Carolin Frueh, an astrodynamical
                    researcher
                    at Purdue University in West Lafayette, Indiana.
                </p>

                <h3>C</h3>
                <p>
                    Even as our ability to monitor space objects increases, so too does the total number of items in
                    orbit. That means companies, governments and other players in space are collaborating in new ways to
                    avoid a shared threat. International groups such as the Inter-Agency Space Debris Coordination
                    Committee have developed guidelines on space sustainability. Those include inactivating satellites
                    at the end of their useful life by venting pressurised materials or leftover fuel that might lead to
                    explosions. The intergovernmental groups also advise lowering satellites deep enough into the
                    atmosphere that they will burn up or disintegrate within 25 years. But so far, only about half of
                    all
                    missions have abided by this 25-year goal, says Holger Krag, head of the European Space Agency’s
                    space-debris office in Darmstadt, Germany. Operators of the planned large constellations of
                    satellites
                    say they will be responsible stewards in their enterprises in space, but Krag worries that problems
                    could increase, despite their best intentions. ‘What happens to those that fail or go bankrupt?’ he
                    asks. They are probably not going to spend money to remove their satellites from space.’
                </p>

                <h3>D</h3>
                <p>
                    In theory, given the vastness of space, satellite operators should have plenty of room for all these
                    missions to fly safely without ever nearing another object. So some scientists are tackling the
                    problem of space junk by trying to find out where all the debris is to a high degree of precision.
                    That would alleviate the need for many of the unnecessary manoeuvres that are carried out to avoid
                    potential collisions. ‘If you knew precisely where everything was, you would almost never have a
                    problem,’ says Marlon Sorge, a space-debris specialist at the Aerospace Corporation in El Segundo,
                    California.
                </p>

                <h3>E</h3>
                <p>
                    The field is called space traffic management, because it’s similar to managing traffic on the roads
                    or in the air. Think about a busy day at an airport, says Moriba Jah, an astrodynamicist at the
                    University of Texas at Austin: planes line up in the sky, landing and taking off close to one
                    another
                    in a carefully choreographed routine. Air-traffic controllers know the location of the planes down
                    to one metre in accuracy. The same can’t be said for space debris. Not all objects in orbit are
                    known,
                    and even those included in databases are not tracked consistently.
                </p>

                <h3>F</h3>
                <p>
                    An additional problem is that there is no authoritative catalogue that accurately lists the orbits
                    of all known space debris. Jah illustrates this with a web-based database that he has developed. It
                    draws on several sources, such as catalogues maintained by the US and Russian governments, to
                    visualise where objects are in space. When he types in an identifier for a particular space object,
                    the database draws a purple line to designate its orbit. Only this doesn’t quite work for a number
                    of
                    objects, such as a Russian rocket body designated in the database as object number 32280. When Jah
                    enters that number, the database draws two purple lines: the US and Russian sources contain two
                    completely different orbits for the same object. Jah says that it is almost impossible to tell which
                    is correct, unless a third source of information made it possible to cross-correlate.
                </p>
                <p>
                    Jah describes himself as a space environmentalist: ‘I want to make space a place that is safe to
                    operate, that is free and useful for generations to come.’ Until that happens, he argues, the space
                    community will continue devolving into a tragedy in which all spaceflight operators are polluting a
                    common resource.
                </p>

