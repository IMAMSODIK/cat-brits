<p class="passage-title">Green Wave Washes Over Mainstream Shopping</p>
<div class="passage-body">
    <p>
        Research in Britain has shown that green consumers continue to flourish as a
        significant group amongst shoppers.This suggests that politicians who claim
        environmentalism is yesterday's issue may be seriously misjudging the public mood.
    </p>
    <p>
        A report from Mintel, the market research organisation, says that despite recession and
        financial pressures, more people than ever want to buy environmentally friendly
        products and a 'green wave' has swept through consumerism, taking in people
        previously untouched by environmental concerns.The recently published report also
        predicts that the process will repeat itself with 'ethical' concerns, involving issues such
        as fair trade with the Third World and the social record of businesses.Companies will
        have to be more honest and open in response to this mood.
    </p>
    <p>
        Mintel's survey, based on nearly 1,000 consumers, found that the proportion who look
        for green products and are prepared to pay more for them has climbed from 53 per cent
        in 1990 to around 60 per cent in 1994.On average, they will pay 13 per cent more for
        such products, although this percentage is higher among women, managerial and
        professional groups and those aged 35 to 44.
    </p>
    <p>
        Between 1990 and 1994 the proportion of consumers claiming to be unaware of or
        unconcerned about green issues fell from 18 to 10 per cent but the number of green
        spenders among older people and manual workers has risen substantially.Regions such
        as Scotland have also caught up with the south of England in their environmental
        concerns.According to Mintel, the image of green consumerism as associated in the
        past with the more eccentric members of society has virtually disappeared.The
        consumer research manager for Mintel, Angela Hughes, said it had become firmly
        established as a mainstream market.She explained that as far as the average person is
        concerned environmentalism has not "gone off the boil".In fact, it has spread across a
        much wider range of consumer groups, ages and occupations
    </p>
    <p>
        Mintel's 1994 survey found that 13 per cent of consumers are 'very dark green', nearly
        always buying environmentally friendly products, 28 per cent are 'dark green', trying 'as
        far as possible' to buy such products, and 21 per cent are 'pale green' - tending to buy
        green products if they see them.Another 26 per cent are 'armchair greens'; they said
        they care about environmental issues but their concern does not affect their spending
        habits.Only 10 per cent say they do not care about green issues.
    </p>
    <p>
        Four in ten people are 'ethical spenders', buying goods which do not, for example,
        involve dealings with oppressive regimes.This figure is the same as in 1990, although
        the number of 'armchair ethicals' has risen from 28 to 35 per cent and only 22 per cent
        say they are unconcerned now, against 30 per cent in 1990.Hughes claims that in the
        twenty-first century, consumers will be encouraged to think more about the entire history
        of the products and services they buy, including the policies of the companies that
        provide them and that this will require a greater degree of honesty with consumers.
    </p>
    <p>
        Among green consumers, animal testing is the top issue - 48 per cent said they would
        be deterred from buying a product it if had been tested on animals - followed by
        concerns regarding irresponsible selling, the ozone layer, river and sea pollution, forest
        destruction, recycling and factory farming.However, concern for specific issues is lower
        than in 1990, suggesting that many consumers feel that Government and business have
        taken on the environmental agenda.
    </p>
</div>
