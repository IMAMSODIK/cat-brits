                <div class="passage-title">New Zealand Seaweed</div>
                <div class="passage-body">
                    <b>Call us not weeds; we are flowers of the sea.</b>
                    <h3>A</h3>
                    <p>
                        Seaweed is a particularly nutritious food, which absorbs and concentrates traces of a
                        wide variety of minerals necessary to the body’s health. Many elements may occur in
                        seaweed – aluminium, barium, calcium, chlorine, copper, iodine and iron, to name but a
                        few – traces normally produced by erosion and carried to the seaweed beds by river and
                        sea currents. Seaweeds are also rich in vitamins: indeed, Eskimos obtain a high
                        proportion of their bodily requirements of vitamin C from the seaweeds they eat.
                    </p>
                    <p>
                        The nutritive value of seaweed has long been recognised. For instance, there is a
                        remarkably low incidence of goitre amongst the Japanese, and for that matter, amongst
                        our own Maori people, who have always eaten seaweeds, and this may well be
                        attributed to the high iodine content of this food. Research into old Maori eating customs
                        shows that jellies were made using seaweeds, fresh fruit and nuts, fuchsia and tutu
                        berries, cape gooseberries, and many other fruits which either grew here naturally or
                        were sown from seeds brought by settlers and explorers.
                    </p>
                    <h3>B</h3>
                    <p>
                        New Zealand lays claim to approximately 700 species of seaweed, some of which have
                        no representation outside this country. Of several species grown worldwide, New
                        Zealand also has a particularly large share. For example, it is estimated that New
                        Zealand has some 30 species of Gigartina, a close relative of carrageen or Irish moss.
                        These are often referred to as the New Zealand carrageens. The gel-forming substance
                        called agar which can be extracted from this species gives them great commercial
                        application in seameal, from which seameal custard is made, and in cough mixture,
                        confectionery, cosmetics, the canning, paint and leather industries, the manufacture of
                        duplicating pads, and in toothpaste. In fact, during World War II, New Zealand Gigartina
                        were sent to Australia to be used in toothpaste.
                    </p>
                    <h3>C</h3>
                    <p>
                        Yet although New Zealand has so much of the commercially profitable red seaweeds,
                        several of which are a source of agar (Pterocladia, Gelidium, Chondrus, Gigartina),
                        before 1940 relatively little use was made of them. New Zealand used to import the
                        Northern Hemisphere Irish moss (Chondrus crispus) from England and ready-made agar
                        from Japan. Although distribution of the Gigartina is confined to certain areas according
                        to species, it is only on the east coast of the North Island that its occurrence is rare. And
                        even then, the east coast, and the area around Hokiangna, have a considerable supply
                        of the two species of Pterocladia from which agar is also available. Happily, New
                        Zealand-made agar is now obtainable in health food shops.
                    </p>
                    <h3>D</h3>
                    <p>
                        Seaweeds are divided into three classes determined by colour – red, brown and green –
                        and each tends to live in a specific location. However, except for the unmistakable sea
                        lettuce (Ulva), few are totally one colour; and especially when dry, some species can
                        change colour quite significantly – a brown one may turn quite black, or a red one
                        appear black, brown, pink or purple.
                    </p>
                    <p>
                        Identification is nevertheless facilitated by the fact that the factors which determine
                        where a seaweed will grow are quite precise, and they therefore tend to occur in very
                        well-defined zones. Although there are exceptions, the green seaweeds are mainly
                        shallow-water algae; the browns belong to medium depths, and the reds are plants of
                        the deeper water. Flat rock surfaces near mid-level tides are the most usual habitat of
                        sea bombs, Venus’ necklace and most brown seaweeds. This is also the location of the
                        purple laver or Maori karengo, which looks rather like a reddish-purple lettuce.
                        Deep-water rocks on open coasts, exposed only at very low tide, are usually the site of
                        bull kelp, strap weeds and similar tough specimens. Those species able to resist long
                        periods of exposure to the sun and air are usually found on the upper shore, while those
                        less able to stand such exposure occur nearer to or below the low-water mark. Radiation
                        from the sun, the temperature level, and the length of time immersed all play a part in
                        the zoning of seaweeds.
                    </p>
                    <h3>E</h3>
                    <p>
                        Propagation of seaweeds occurs by spores, or by fertilisation of egg cells. None have
                        roots in the usual sense; few have leaves, and none have flowers, fruits or seeds. The
                        plants absorb their nourishment through their fronds when they are surrounded by
                        water: the base or “holdfast” of seaweeds is purely an attaching organ, not an absorbing
                        one.
                    </p>
                    <h3>F</h3>
                    <p>
                        Some of the large seaweeds maintain buoyancy with air-filled floats; others, such as bull
                        kelp, have large cells filled with air. Some, which spend a good part of their time exposed
                        to the air, often reduce dehydration either by having swollen stems that contain water, or
                        they may (like Venus’ necklace) have | swollen nodules, or they may have a distinctive
                        shape like a sea bomb. Others, like the sea cactus, are filled with slimy fluid or have a
                        coating of mucilage on the surface. In some of the larger kelps, this coating is not only to
                        keep the plant moist but also to protect it from the violent action of waves.
                    </p>
