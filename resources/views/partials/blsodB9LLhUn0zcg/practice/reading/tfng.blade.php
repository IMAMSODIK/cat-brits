                <p><b>Why we need to protect polar bears</b></p>
                <p>Polar bears are being increasingly threatened by the effects of climate change, but their
                    disappearance could have far-reaching consequences. They are uniquely adapted to the extreme
                    conditions of the Arctic Circle, where temperatures can reach —40°C. One reason for this is that
                    they have up to 11 centimetres of fat underneath their skin. Humans with comparative levels of
                    adipose tissue would be considered obese and would be likely to suffer from diabetes and heart
                    disease. Yet the polar bear experiences no such consequences.</p>
                <p>A 2014 study by Shi Ping Liu and colleagues sheds light on this mystery. They compared the genetic
                    structure of polar bears with that of their closest relatives from a warmer climate, the brown
                    bears. This allowed them to determine the genes that have allowed polar bears to survive in one of
                    the toughest environments on Earth. Liu and his colleagues found the polar bears had a gene known as
                    APoB, which reduces levels of low-density lipoproteins (LDLs) – a form of ‘bad’ cholesterol. In
                    humans, mutations of this gene are associated with increased risk of heart disease. Polar bears may
                    therefore be an important study model to understand heart disease in humans.</p>
                <p>The genome of the polar bear may also provide the solution for another condition, one that
                    particularly affects our older generation: osteoporosis. This is a disease where bones show reduced
                    density, usually caused by insufficient exercise, reduced calcium intake or food starvation. Bone
                    tissue is constantly being remodelled, meaning that bone is added or removed, depending on nutrient
                    availability and the stress that the bone is under.</p>
                <p>Female polar bears, however, undergo extreme conditions during every pregnancy. Once autumn comes
                    around, these females will dig maternity dens in the snow and will remain there throughout the
                    winter, both before and after the birth of their cubs. This process results in about six months of
                    fasting, where the female bears have to keep themselves and their cubs alive, depleting their own
                    calcium and calorie reserves. Despite this, their bones remain strong and dense.</p>
                <p>Physiologists Alanda Lennox and Allen Goodship found an explanation for this paradox in 2008. They
                    discovered that pregnant bears were able to increase the density of their bones before they started
                    to build their dens. In addition, six months later, when they finally emerged from the den with
                    their cubs, there was no evidence of significant loss of bone density. Hibernating brown bears do
                    not have this capacity and must therefore resort to major bone reformation in the following spring.
                    If the mechanism of bone remodelling in polar bears can be understood, many bedridden humans, and
                    even astronauts, could potentially benefit.</p>
