            <h3 class="passage-title">The persistence and peril of misinformation</h3>
            <div class="passage-body">
                <p>
                    Misinformation – both deliberately promoted and accidentally shared – is perhaps an
                    inevitable part of the world in which we live, but it is not a new problem. People likely
                    have lied to one another for roughly as long as verbal communication has existed. Deceiving
                    others can offer an apparent opportunity to gain strategic advantage, to motivate others
                    to action, or even to protect interpersonal bonds. Moreover, people inadvertently have been
                    sharing inaccurate information with one another for thousands of years.
                </p>

                <p>
                    However, we currently live in an era in which technology enables information to reach large
                    audiences distributed across the globe, and thus the potential for immediate and widespread
                    effects from misinformation now looms larger than in the past. Yet the means to correct
                    misinformation might, over time, be found in those same patterns of mass communication and
                    of the facilitated spread of information.
                </p>

                <p>
                    The main worry regarding misinformation is its potential to unduly influence attitudes and
                    behavior, leading people to think and act differently than they would if they were correctly
                    informed, as suggested by the research teams of Stephan Lewandowsky of the University of
                    Bristol and Elizabeth Marsh of Duke University, among others. In other words, we worry that
                    misinformation might lead people to hold misperceptions (or false beliefs) and that these
                    misperceptions, especially when they occur among large groups of people, may have
                    detrimental, downstream consequences for health, social harmony, and the political climate.
                </p>

                <p>
                    At least three observations related to misinformation in the contemporary mass-media
                    environment warrant the attention of researchers, policy makers, and really everyone who
                    watches television, listens to the radio, or reads information online. First of all, people
                    who encounter misinformation tend to believe it, at least initially. Secondly, electronic
                    and print media often do not block many types of misinformation before it appears in content
                    available to large audiences. Thirdly, countering misinformation once it has enjoyed wide
                    exposure can be a resource-intensive effort.
                </p>

                <p>
                    Knowing what happens when people initially encounter misinformation holds tremendous
                    importance for estimating the potential for subsequent problems. Although it is fairly
                    routine for individuals to come across information that is false, the question of exactly
                    how – and when – we mentally label information as true or false has garnered philosophical
                    debate. The dilemma is neatly summarized by a contrast between how the 17th-century
                    philosophers Rene Descartes and Baruch Spinoza described human information engagement, with
                    conflicting predictions that only recently have been empirically tested in robust ways.
                    Descartes argued that a person only accepts or rejects information after considering its
                    truth or falsehood; Spinoza argued that people accept all encountered information (or
                    misinformation) by default and then subsequently verify or reject it through a separate
                    cognitive process. In recent decades, empirical evidence has supported Spinoza’s account:
                    people appear to encode all new information as if it were true, even if only momentarily,
                    and later tag the information as being either true or false.
                </p>

                <p>
                    What about the observation that misinformation often can appear in electronic or print
                    media without being preemptively blocked? One explanation lies in the nature of regulatory
                    structures, particularly in the United States, where regulatory agencies tend to focus on
                    post hoc detection of broadcast information rather than preemptive censoring. Although such
                    systems allow for monitoring and reporting, they do not prevent false information from
                    reaching the public. In addition, even misinformation that is successfully corrected can
                    continue to affect attitudes.
                </p>
            </div>

