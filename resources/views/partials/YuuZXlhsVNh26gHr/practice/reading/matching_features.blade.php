                <h3>G</h3>
                <p>
                    The Hamiltonian view, which is similar to the Platonic view, is that people are born
                    with different levels of intelligence and that those who are less intelligent need
                    the good offices of the more intelligent to keep them in line, whether they are
                    called government officials or, in Plato’s term, philosopher-kings. Herrnstein and
                    Murray (1994) seem to have shared this belief when they wrote about the emergence of a
                    cognitive (high-IQ) elite, which eventually would have to take responsibility for
                    the largely irresponsible masses of non-elite (low-IQ) people who cannot take care
                    of themselves. Left to themselves, the unintelligent would create, as they always
                    have created, a kind of chaos.
                </p>

                <h3>H</h3>
                <p>
                    The Jeffersonian view is that people should have equal opportunities, but they do
                    not necessarily avail themselves equally of these opportunities and are not
                    necessarily equally rewarded for their accomplishments. People are rewarded for
                    what they accomplish, if given equal opportunity. Low achievers are not rewarded to
                    the same extent as high achievers. In the Jeffersonian view, the goal of education
                    is not to favor or foster an elite, as in the Hamiltonian tradition, but rather to
                    allow children the opportunities to make full use of the skills they have. My own
                    views are similar to these (Sternberg, 1997).
                </p>

                <h3>I</h3>
                <p>
                    The Jacksonian view is that all people are equal, not only as human beings but in
                    terms of their competencies – that one person would serve as well as another in
                    government or on a jury or in almost any position of responsibility. In this view
                    of democracy, people are essentially intersubstitutable except for specialized
                    skills, all of which can be learned. In this view, we do not need or want any
                    institutions that might lead to favoring one group over another.
                </p>

