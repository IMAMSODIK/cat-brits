                    <h2><b>Saving bugs to find new drugs</b></h3>
                        <p><i>Zoologist Ross Piper looks at the potential of insects in pharmaceutical research</i></p>
                        <h3 class="passage-title">A</h3>
                        <p>
                            More drugs than you might think are derived from, or inspired by, compounds found in living
                            things. Looking to nature for the soothing and curing of our ailments is nothing new – we
                            have been doing it for tens of thousands of years. You only have to look at other primates –
                            such as the capuchin monkeys who rub themselves with toxin-oozing millipedes to deter
                            mosquitoes, or the chimpanzees who use noxious forest plants to rid themselves of intestinal
                            parasites – to realise that our ancient ancestors too probably had a basic grasp of
                            medicine.
                        </p>

                        <h3 class="passage-title">B</h3>
                        <p>
                            Pharmaceutical science and chemistry built on these ancient foundations and perfected the
                            extraction, characterization, modification and testing of these natural products. Then, for
                            a while, modern pharmaceutical science moved its focus away from nature and into the
                            laboratory, designing chemical compounds from scratch. The main cause of this shift is that
                            although there are plenty of promising chemical compounds in nature, finding them is far
                            from easy. Securing sufficient numbers of the organism in question, isolating and
                            characterizing the compounds of interest, and producing large quantities of these compounds
                            are all significant hurdles.
                        </p>

                        <h3 class="passage-title">C</h3>
                        <p>
                            Laboratory-based drug discovery has achieved varying levels of success, something which has
                            now prompted the development of new approaches focusing once again on natural products. With
                            the ability to mine genomes for useful compounds, it is now evident that we have barely
                            scratched the surface of nature’s molecular diversity. This realization, together with
                            several looming health crises, such as antibiotic resistance, has put bioprospecting – the
                            search for useful compounds in nature – firmly back on the map.
                        </p>

                        <h3 class="passage-title">D</h3>
                        <p>
                            Insects are the undisputed masters of the terrestrial domain, where they occupy every
                            possible niche. Consequently, they have a bewildering array of interactions with other
                            organisms, something which has driven the evolution of an enormous range of very interesting
                            compounds for defensive and offensive purposes. Their remarkable diversity exceeds that of
                            every other group of animals on the planet combined. Yet even though insects are far and
                            away the most diverse animals in existence, their potential as sources of therapeutic
                            compounds is yet to be realised.
                        </p>

                        <h3 class="passage-title">E</h3>
                        <p>
                            From the tiny proportion of insects that have been investigated, several promising compounds
                            have been identified. For example, alloferon, an antimicrobial compound produced by blow fly
                            larvae, is used as an antiviral and antitumor agent in South Korea and Russia. The larvae of
                            a few other insect species are being investigated for the potent antimicrobial compounds
                            they produce. Meanwhile, a compound from the venom of the wasp Polybia paulista has
                            potential in cancer treatment.
                        </p>

                        <h3 class="passage-title">F</h3>
                        <p>
                            Why is it that insects have received relatively little attention in bioprospecting? Firstly,
                            there are so many insects that, without some manner of targeted approach, investigating this
                            huge variety of species is a daunting task. Secondly, insects are generally very small, and
                            the glands inside them that secrete potentially useful compounds are smaller still. This can
                            make it difficult to obtain sufficient quantities of the compound for subsequent testing.
                            Thirdly, although we consider insects to be everywhere, the reality of this ubiquity is vast
                            numbers of a few extremely common species. Many insect species are infrequently encountered
                            and very difficult to rear in captivity, which, again, can leave us with insufficient
                            material to work with.
                        </p>

                        <h3 class="passage-title">G</h3>
                        <p>
                            My colleagues and I at Aberystwyth University in the UK have developed an approach in which
                            we use our knowledge of ecology as a guide to target our efforts. The creatures that
                            particularly interest us are the many insects that secrete powerful poison for subduing prey
                            and keeping it fresh for future consumption. There are even more insects that are masters of
                            exploiting filthy habitats, such as faeces and carcasses, where they are regularly
                            challenged by thousands of micro-organisms. These insects have many antimicrobial compounds
                            for dealing with pathogenic bacteria and fungi, suggesting that there is certainly potential
                            to find many compounds that can serve as or inspire new antibiotics.
                        </p>

                        <h3 class="passage-title">H</h3>
                        <p>
                            Although natural history knowledge points us in the right direction, it doesn’t solve the
                            problems associated with obtaining useful compounds from insects. Fortunately, it is now
                            possible to snip out the stretches of the insect’s DNA that carry the codes for the
                            interesting compounds and insert them into cell lines that allow larger quantities to be
                            produced. And although the road from isolating and characterizing compounds with desirable
                            qualities to developing a commercial product is very long and full of pitfalls, the variety
                            of successful animal-derived pharmaceuticals on the market demonstrates there is a precedent
                            here that is worth exploring.
                        </p>

                        <h3 class="passage-title">I</h3>
                        <p>
                            With every bit of wilderness that disappears, we deprive ourselves of potential medicines.
                            As much as I’d love to help develop a groundbreaking insect-derived medicine, my main
                            motivation for looking at insects in this way is conservation. I sincerely believe that all
                            species, however small and seemingly insignificant, have a right to exist for their own
                            sake. If we can shine a light on the darker recesses of nature’s medicine cabinet, exploring
                            the useful chemistry of the most diverse animals on the planet, I believe we can make people
                            think differently about the value of nature.
                        </p>

