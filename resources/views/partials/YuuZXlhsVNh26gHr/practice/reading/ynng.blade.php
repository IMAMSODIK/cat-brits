                <h3>B</h3>
                <p>
                    First, implicit theories of intelligence drive the way in which people perceive and evaluate their
                    own intelligence and that of others. To better understand the judgments people make about their own
                    and others’ abilities, it is useful to learn about people’s implicit theories. For example, parents’
                    implicit theories of their children’s language development will determine at what ages they will be
                    willing to make various corrections in their children’s speech. More generally, parents’ implicit
                    theories of intelligence will determine at what ages they believe their children are ready to
                    perform various cognitive tasks. Job interviewers will make hiring decisions on the basis of their
                    implicit theories of intelligence. People will decide who to be friends with on the basis of such
                    theories. In sum, knowledge about implicit theories of intelligence is important because this
                    knowledge is so often used by people to make judgments in the course of their everyday lives.
                </p>

                <h3>C</h3>
                <p>
                    Second, the implicit theories of scientific investigators ultimately give rise to their explicit
                    theories. Thus it is useful to find out what these implicit theories are. Implicit theories provide
                    a
                    framework that is useful in defining the general scope of a phenomenon – especially a
                    not-well-understood phenomenon. These implicit theories can suggest what aspects of the phenomenon
                    have been more or less attended to in previous investigations.
                </p>

                <h3>D</h3>
                <p>
                    Third, implicit theories can be useful when an investigator suspects that existing explicit theories
                    are wrong or misleading. If an investigation of implicit theories reveals little correspondence
                    between the extant implicit and explicit theories, the implicit theories may be wrong. But the
                    possibility also needs to be taken into account that the explicit theories are wrong and in need of
                    correction or supplementation. For example, some implicit theories of intelligence suggest the need
                    for expansion of some of our explicit theories of the construct.
                </p>

                <h3>E</h3>
                <p>
                    Finally, understanding implicit theories of intelligence can help elucidate developmental and
                    cross-cultural differences. As mentioned earlier, people have expectations for intellectual
                    performances that differ for children of different ages. How these expectations differ is in part a
                    function of culture. For example, expectations for children who participate in Western-style
                    schooling are almost certain to be different from those for children who do not participate in such
                    schooling.
                </p>

                <h3>F</h3>
                <p>
                    I have suggested that there are three major implicit theories of how intelligence relates to society
                    as a whole (Sternberg, 1997). These might be called Hamiltonian, Jeffersonian, and Jacksonian. These
                    views are not based strictly, but rather, loosely, on the philosophies of Alexander Hamilton, Thomas
                    Jefferson, and Andrew Jackson, three great statesmen in the history of the United States.
                </p>

                <h3>G</h3>
                <p>
                    The Hamiltonian view, which is similar to the Platonic view, is that people are born with different
                    levels of intelligence and that those who are less intelligent need the good offices of the more
                    intelligent to keep them in line, whether they are called government officials or, in Plato’s term,
                    philosopher-kings. Herrnstein and Murray (1994) seem to have shared this belief when they wrote
                    about
                    the emergence of a cognitive (high-IQ) elite, which eventually would have to take responsibility for
                    the largely irresponsible masses of non-elite (low-IQ) people who cannot take care of themselves.
                    Left to themselves, the unintelligent would create, as they always have created, a kind of chaos.
                </p>

                <h3>H</h3>
                <p>
                    The Jeffersonian view is that people should have equal opportunities, but they do not necessarily
                    avail themselves equally of these opportunities and are not necessarily equally rewarded for their
                    accomplishments. People are rewarded for what they accomplish, if given equal opportunity. Low
                    achievers are not rewarded to the same extent as high achievers. In the Jeffersonian view, the goal
                    of education is not to favor or foster an elite, as in the Hamiltonian tradition, but rather to
                    allow
                    children the opportunities to make full use of the skills they have. My own views are similar to
                    these (Sternberg, 1997).
                </p>

                <h3>I</h3>
                <p>
                    The Jacksonian view is that all people are equal, not only as human beings but in terms of their
                    competencies – that one person would serve as well as another in government or on a jury or in
                    almost any position of responsibility. In this view of democracy, people are essentially
                    intersubstitutable except for specialized skills, all of which can be learned. In this view, we do
                    not need or want any institutions that might lead to favoring one group over another.
                </p>

                <h3>J</h3>
                <p>
                    Implicit theories of intelligence and of the relationship of intelligence to society perhaps need
                    to be considered more carefully than they have been because they often serve as underlying
                    presuppositions for explicit theories and even experimental designs that are then taken as
                    scientific contributions. Until scholars are able to discuss their implicit theories and thus their
                    assumptions, they are likely to miss the point of what others are saying when discussing their
                    explicit theories and their data.
                </p>

