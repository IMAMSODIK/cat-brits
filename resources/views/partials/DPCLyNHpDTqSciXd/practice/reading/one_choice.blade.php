                <h3>Insight or evolution?</h3>
            </div>
            <div class="passage-body">
                <p>
                    Two scientists consider the origins of discoveries and other innovative behavior
                </p>

                <p>
                    Scientific discovery is popularly believed to result from the sheer genius of such intellectual
                    stars as
                    naturalist Charles Darwin and theoretical physicist Albert Einstein. Our view of such unique
                    contributions to
                    science often disregards the person’s prior experience and the efforts of their lesser-known
                    predecessors.
                    Conventional wisdom also places great weight on insight in promoting breakthrough scientific
                    achievements, as if
                    ideas spontaneously pop into someone’s head – fully formed and functional.
                </p>

                <p>
                    There may be some limited truth to this view. However, we believe that it largely misrepresents the
                    real nature
                    of scientific discovery, as well as that of creativity and innovation in many other realms of human
                    endeavor.
                </p>

                <p>
                    Setting aside such greats as Darwin and Einstein – whose monumental contributions are duly
                    celebrated – we
                    suggest that innovation is more a process of trial and error, where two steps forward may sometimes
                    come with
                    one step back, as well as one or more steps to the right or left. This evolutionary view of human
                    innovation
                    undermines the notion of creative genius and recognizes the cumulative nature of scientific
                    progress.
                </p>

                <p>
                    Consider one unheralded scientist: John Nicholson, a mathematical physicist working in the 1910s who
                    postulated
                    the existence of‘proto-elements’ in outer space. By combining different numbers of weights of these
                    proto-elements’ atoms, Nicholson could recover the weights of all the elements in the then-known
                    periodic table.
                    These successes are all the more noteworthy given the fact that Nicholson was wrong about the
                    presence of
                    proto-elements: they do not actually exist. Yet, amid his often fanciful theories and wild
                    speculations,
                    Nicholson also proposed a novel theory about the structure of atoms. Niels Bohr, the Nobel
                    prize-winning father
                    of modern atomic theory, jumped off from this interesting idea to conceive his now-famous model of
                    the atom.
                </p>

                <p>
                    What are we to make of this story? One might simply conclude that science is a collective and
                    cumulative
                    enterprise. That may be true, but there may be a deeper insight to be gleaned. We propose that
                    science is
                    constantly evolving, much as species of animals do. In biological systems, organisms may display new
                    characteristics that result from random genetic mutations. In the same way, random, arbitrary or
                    accidental
                    mutations of ideas may help pave the way for advances in science. If mutations prove beneficial,
                    then the animal
                    or the scientific theory will continue to thrive and perhaps reproduce.
                </p>

                <p>
                    Support for this evolutionary view of behavioral innovation comes from many domains. Consider one
                    example of an
                    influential innovation in US horseracing. The so-called ‘acey-deucy’ stirrup placement, in which the
                    rider’s
                    foot in his left stirrup is placed as much as 25 centimeters lower than the right, is believed to
                    confer
                    important speed advantages when turning on oval tracks. It was developed by a relatively unknown
                    jockey named
                    Jackie Westrope. Had Westrope conducted methodical investigations or examined extensive film records
                    in a shrewd
                    plan to outrun his rivals? Had he foreseen the speed advantage that would be conferred by riding
                    acey-deucy? No.
                    He suffered a leg injury, which left him unable to fully bend his left knee. His modification just
                    happened to
                    coincide with enhanced left-hand turning performance. This led to the rapid and widespread adoption
                    of riding
                    acey-deucy by many riders, a racing style which continues in today’s thoroughbred racing.
                </p>

            </div>
