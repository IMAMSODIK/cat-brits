                <p><b>The Dead Sea Scrolls</b></p>
                <p>In late 1946 or early 1947, three Bedouin teenagers were tending their goats and sheep near the
                    ancient settlement of Qumran, located on the northwest shore of the Dead Sea in what is now known as
                    the West Bank. One of these young shepherds tossed a rock into an opening on the side of a cliff and
                    was surprised to hear a shattering sound. He and his companions later entered the cave and stumbled
                    across a collection of large clay jars, seven of which contained scrolls with writing on them. The
                    teenagers took the seven scrolls to a nearby town where they were sold for a small sum to a local
                    antiquities dealer. Word of the find spread, and Bedouins and archaeologists eventually unearthed
                    tens of thousands of additional scroll fragments from 10 nearby caves; together they make up between
                    800 and 900 manuscripts. It soon became clear that this was one of the greatest archaeological
                    discoveries ever made.</p>
                <p>The origin of the Dead Sea Scrolls, which were written around 2,000 years ago between 150 BCE and 70
                    CE, is still the subject of scholarly debate even today. According to the prevailing theory, they
                    are the work of a population that inhabited the area until Roman troops destroyed the settlement
                    around 70 CE. The area was known as Judea at that time, and the people are thought to have belonged
                    to a group called the Essenes, a devout Jewish sect.</p>
                <p>The majority of the texts on the Dead Sea Scrolls are in Hebrew, with some fragments written in an
                    ancient version of its alphabet thought to have fallen out of use in the fifth century BCE. But
                    there are other languages as well. Some scrolls are in Aramaic, the language spoken by many
                    inhabitants of the region from the sixth century BCE to the siege of Jerusalem in 70 CE. In
                    addition, several texts feature translations of the Hebrew Bible into Greek.</p>
                <p>The Dead Sea Scrolls include fragments from every book of the Old Testament of the Bible except for
                    the Book of Esther. The only entire book of the Hebrew Bible preserved among the manuscripts from
                    Qumran is Isaiah; this copy, dated to the first century BCE, is considered the earliest biblical
                    manuscript still in existence. Along with biblical texts, the scrolls include documents about
                    sectarian regulations and religious writings that do not appear in the Old Testament.</p>
                <p>The writing on the Dead Sea Scrolls is mostly in black or occasionally red ink, and the scrolls
                    themselves are nearly all made of either parchment (animal skin) or an early form of paper called
                    ‘papyrus’. The only exception is the scroll numbered 3Q15, which was created out of a combination of
                    copper and tin. Known as the Copper Scroll, this curious document features letters chiselled onto
                    metal – perhaps, as some have theorized, to better withstand the passage of time. One of the most
                    intriguing manuscripts from Qumran, this is a sort of ancient treasure map that lists dozens of gold
                    and silver caches. Using an unconventional vocabulary and odd spelling, it describes 64 underground
                    hiding places that supposedly contain riches buried for safekeeping. None of these hoards have been
                    recovered, possibly because the Romans pillaged Judea during the first century CE. According to
                    various hypotheses, the treasure belonged to local people, or was rescued from the Second Temple
                    before its destruction or never existed to begin with.</p>
                <p>Some of the Dead Sea Scrolls have been on interesting journeys. In 1948, a Syrian Orthodox archbishop
                    known as Mar Samuel acquired four of the original seven scrolls from a Jerusalem shoemaker and
                    part-time antiquity dealer, paying less than $100 for them. He then travelled to the United States
                    and unsuccessfully offered them to a number of universities, including Yale. Finally, in 1954, he
                    placed an advertisement in the business newspaper The Wall Street Journal – under the category
                    ‘Miscellaneous Items for Sale’ – that read: ‘Biblical Manuscripts dating back to at least 200 B.C.
                    are for sale. This would be an ideal gift to an educational or religious institution by an
                    individual or group.’ Fortunately, Israeli archaeologist and statesman Yigael Yadin negotiated their
                    purchase and brought the scrolls back to Jerusalem, where they remain to this day.</p>
                <p>In 2017, researchers from the University of Haifa restored and deciphered one of the last
                    untranslated scrolls. The university’s Eshbal Ratson and Jonathan Ben-Dov spent one year
                    reassembling the 60 fragments that make up the scroll. Deciphered from a band of coded text on
                    parchment, the find provides insight into the community of people who wrote it and the 364-day
                    calendar they would have used. The scroll names celebrations that indicate shifts in seasons and
                    details two yearly religious events known from another Dead Sea Scroll. Only one more known scroll
                    remains untranslated.</p>
