                <h3>A</h3>
                <p>
                    It took at least 3,000 years for humans to learn how to domesticate the wild tomato and cultivate it
                    for food. Now two separate teams in Brazil and China have done it all over again in less than three
                    years. And they have done it better in some ways, as the re-domesticated tomatoes are more
                    nutritious than the ones we eat at present.
                </p>
                <p>
                    This approach relies on the revolutionary CRISPR genome editing technique, in which changes are
                    deliberately made to the DNA of a living cell, allowing genetic material to be added, removed or
                    altered. The technique could not only improve existing crops, but could also be used to turn
                    thousands of wild plants into useful and appealing foods. In fact, a third team in the US has
                    already begun to do this with a relative of the tomato called the groundcherry.
                </p>
                <p>
                    This fast-track domestication could help make the world’s food supply healthier and far more
                    resistant to diseases, such as the rust fungus devastating wheat crops.
                </p>
                <p>
                    ‘This could transform what we eat,’ says Jorg Kudla at the University of Munster in Germany, a
                    member of the Brazilian team. ‘There are 50,000 edible plants in the world, but 90 percent of our
                    energy comes from just 15 crops.’
                </p>
                <p>
                    ‘We can now mimic the known domestication course of major crops like rice, maize, sorghum or
                    others,’ says Caixia Gao of the Chinese Academy of Sciences in Beijing. Then we might try to
                    domesticate plants that have never been domesticated.’
                </p>

                <h3>B</h3>
                <p>
                    Wild tomatoes, which are native to the Andes region in South America, produce pea-sized fruits. Over
                    many generations, peoples such as the Aztecs and Incas transformed the plant by selecting and
                    breeding plants with mutations* in their genetic structure, which resulted in desirable traits such
                    as larger fruit.
                </p>
                <p>
                    But every time a single plant with a mutation is taken from a larger population for breeding, much
                    genetic diversity is lost. And sometimes the desirable mutations come with less desirable traits.
                    For instance, the tomato strains grown for supermarkets have lost much of their flavour.
                </p>
                <p>
                    By comparing the genomes of modern plants to those of their wild relatives, biologists have been
                    working out what genetic changes occurred as plants were domesticated. The teams in Brazil and China
                    have now used this knowledge to reintroduce these changes from scratch while maintaining or even
                    enhancing the desirable traits of wild strains.
                </p>

                <h3>C</h3>
                <p>
                    Kudla’s team made six changes altogether. For instance, they tripled the size of fruit by editing a
                    gene called FRUIT WEIGHT, and increased the number of tomatoes per truss by editing another called
                    MULTIFLORA.
                </p>
                <p>
                    While the historical domestication of tomatoes reduced levels of the red pigment lycopene – thought
                    to have potential health benefits – the team in Brazil managed to boost it instead. The wild tomato
                    has twice as much lycopene as cultivated ones; the newly domesticated one has five times as much.
                </p>
                <p>
                    ‘They are quite tasty,’ says Kudla. ‘A little bit strong. And very aromatic.’
                </p>
                <p>
                    The team in China re-domesticated several strains of wild tomatoes with desirable traits lost in
                    domesticated tomatoes. In this way they managed to create a strain resistant to a common disease
                    called bacterial spot race, which can devastate yields. They also created another strain that is
                    more salt tolerant – and has higher levels of vitamin C.
                </p>

                <h3>D</h3>
                <p>
                    Meanwhile, Joyce Van Eck at the Boyce Thompson Institute in New York state decided to use the same
                    approach to domesticate the groundcherry or goldenberry (Physalis pruinosa) for the first time. This
                    fruit looks similar to the closely related Cape gooseberry (Physalis peruviana).
                </p>
                <p>
                    Groundcherries are already sold to a limited extent in the US but they are hard to produce because
                    the plant has a sprawling growth habit and the small fruits fall off the branches when ripe. Van
                    Eck’s team has edited the plants to increase fruit size, make their growth more compact and to stop
                    fruits dropping. ‘There’s potential for this to be a commercial crop,’ says Van Eck. But she adds
                    that taking the work further would be expensive because of the need to pay for a licence for the
                    CRISPR technology and get regulatory approval.
                </p>

                <h3>E</h3>
                <p>
                    This approach could boost the use of many obscure plants, says Jonathan Jones of the Sainsbury Lab
                    in the UK. But it will be hard for new foods to grow so popular with farmers and consumers that they
                    become new staple crops, he thinks.
                </p>
                <p>
                    The three teams already have their eye on other plants that could be ‘catapulted into the
                    mainstream’, including foxtail, oat-grass and cowpea. By choosing wild plants that are drought or
                    heat tolerant, says Gao, we could create crops that will thrive even as the planet warms.
                </p>
                <p>
                    But Kudla didn’t want to reveal which species were in his team’s sights, because CRISPR has made the
                    process so easy. ‘Any one with the right skills could go to their lab and do this.’
                </p>
                <p>
                    <i>*mutations: changes in an organism’s genetic structure that can be passed down to later
                        generations</i>
                </p>

