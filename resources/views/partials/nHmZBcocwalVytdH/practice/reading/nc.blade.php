            <h3 class="passage-title">Alexander Henderson (1831-1913)</h3>
            <div class="passage-body">
                <p>Born in Scotland, Henderson emigrated to Canada in 1855 and become a well-known landscape
                    photographer</p>
                <p>Alexander Henderson was born in Scotland in 1831 and was the son of a successful merchant. His
                    grandfather, also called Alexander, had founded the family business, and later became the first
                    chairman of the National Bank of Scotland. The family had extensive landholding in Scotland. Besides
                    its residence in Edinburgh, it owned Press Estate, 650 acres of farmland about 35 miles southeast of
                    the city. The family often stayed at Press Castle, the large mansion on the northern edge of the
                    property, and Alexander spent much of his childhood in the area, playing on the beach near Eyemouth
                    or fishing in the streams nearby.</p>
                <p>Even after he went to school at Murcheston Academy on the outskirts of Edinburgh, Henderson returned
                    to Press at weekends. In 1849 he began a three-year apprenticeship to become an accountant. Although
                    he never liked the prospect of a business career, he stayed with it to please his family. In October
                    1855, however, he emigrated to Canada with his wife Agnes Elder Robertson and they settled in
                    Montreal.</p>
                <p>Henderson learned photography in Montreal around the year 1857 and quickly took it up as a serious
                    amateur. He became a personal friend and colleague of the Scottish – Canadian photographer William
                    Notman. The two men made a photographic excursion to Niagara Falls in 1860 and they cooperated on
                    experiments with magnesium flares as a source of artificial light in 1865. They belonged to the same
                    societies and were among the founding members of the Art Association of Montreal. Henderson acted as
                    chairman of the association’s first meeting, which was held in Notman’s studio on 11 January 1860.
                </p>
                <p>In spite of their friendship, their styles of photography were quite different. While Notman’s
                    landscapes were noted for their bold realism, Henderson for the first 20 years of his career
                    produced romantic images, showing the strong influence of the British landscape tradition. His
                    artistic and technical progress was rapid and in 1865 he published his first major collection of
                    landscape photographs. The publication had limited circulation (only seven copies have ever been
                    found), and was called Canadian Views and Studies. The contents of each copy vary significantly and
                    have proved a useful source for evaluating Henderson’s early work.</p>
                <p>In 1866, he gave up his business to open a photographic studio, advertising himself as a portrait and
                    landscape photographer. From about 1870 he dropped portraiture to specialize in landscape
                    photography and other views. His numerous photographs of city life revealed in street scenes,
                    houses, and markets are alive with human activity, and although his favourite subject was landscape
                    he usually composed his scenes around such human pursuits as farming the land, cutting ice on a
                    river, or sailing down a woodland stream. There was sufficient demand for these types of scenes and
                    others he took depicting the lumber trade, steamboats and waterfalls to enable him to make a living.
                    There was little competing hobby or amateur photography before the late 1880s because of the
                    time-consuming techniques involved and the weight of equipment. People wanted to buy photographs as
                    souvenirs of a trip or as gifts, and catering to this market, Henderson had stock photographs on
                    display at his studio for mounting, framing, or inclusion in albums.</p>
                <p>Henderson frequently exhibited his photographs in Montreal and abroad, in London, Edinburgh, Dublin,
                    Paris, New York, and Philadelphia. He met with greater success in 1877 and 1878 in New York when he
                    won first prizes in the exhibition held by E and H T Anthony and Company for landscapes using the
                    Lambertype process. In 1878 his work won second prize at the world exhibition in Paris.</p>
                <p>In the 1890s and 1880s Henderson travelled widely throughout Quebec and Ontario, in Canada,
                    documenting the major cities of the two provinces and many of the villages in Quebec. He was
                    especially fond of the wilderness and often travelled by canoe on the Blanche, du Lièvre, and other
                    noted eastern rivers. He went on several occasions to the Maritimes and in 1872 he sailed by yacht
                    along the lower north shore of the St Lawrence River. That same year, while in the lower St Lawrence
                    River region, he took some photographs of the construction of the Intercolonial Railway. This
                    undertaking led in 1875 to a commission from the railway to record the principal structures along
                    the almost-completed line connecting Montreal to Halifax. Commissions from other railways followed.
                    In 1876 he photographed bridges on the Quebec, Montreal, Ottawa and Occidental Railway between
                    Montreal and Ottawa. In 1885 he went west along the Canadian Pacific Railway (CPR) as far as Rogers
                    Pass in British Columbia, where he took photographs of the mountains and the progress of
                    construction.</p>
