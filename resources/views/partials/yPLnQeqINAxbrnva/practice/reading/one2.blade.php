                <p>
                    5th paragraph: Readers interested in the specific detail of Wegener’s career will
                    see that he often stopped pursuing a given line of investigation (sometimes for
                    years on end), only to pick it up later. I have tried to provide guideposts to his
                    rapidly shifting interests by characterizing different phases of his life as careers
                    in different sciences, which is reflected in the titles of the chapters. Thus, the
                    index should be a sufficient guide for those interested in a particular aspect of
                    Wegener’s life but perhaps not all of it. My own feeling, however, is that the parts
                    do not make as much sense on their own as do all of his activities taken together.
                    In this respect I urge readers to try to experience Wegener’s life as he lived it,
                    with all the interruptions, changes of mind, and renewed efforts this entailed.
                </p>
                <p>
                    Wegener left behind a few published works but, as was standard practice, these
                    reported the results of his work – not the journey he took to reach that point. Only
                    a few hundred of the many thousands of letters he wrote and received in his lifetime
                    have survived and he didn’t keep notebooks or diaries that recorded his life and
                    activities. He was not active (with a few exceptions) in scientific societies, and
                    did not seek to find influence or advance his ideas through professional contacts
                    and politics, spending most of his time at home in his study reading and writing, or
                    in the field collecting observations.
                </p>
                <p>
                    Some famous scientists, such as Newton, Darwin, and Einstein, left mountains of
                    written material behind, hundreds of notebooks and letters numbering in the tens of
                    thousands. Others, like Michael Faraday, left extensive journals of their thoughts
                    and speculations, parallel to their scientific notebooks. The more such material a
                    scientist leaves behind, the better chance a biographer has of forming an accurate
                    picture of how a scientist’s ideas took shape and evolved.
                </p>
                <p>
                    I am firmly of the opinion that most of us, Wegener included, are not in any real
                    sense the authors of our own lives. We plan, think, and act, often with apparent
                    freedom, but most of the time our lives ‘happen to us’, and we only retrospectively
                    turn this happenstance into a coherent narrative of fulfilled intentions. This book,
                    therefore, is a story both of the life and scientific work that Alfred Wegener
                    planned and intended and of the life and scientific work that actually ‘happened to
                    him’. These are, as I think you will soon see, not always the same thing.
                </p>
