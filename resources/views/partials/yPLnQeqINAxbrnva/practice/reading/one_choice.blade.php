                <h3>The growth mindset</h3>
                <p>
                    Over the past century, a powerful idea has taken root in the educational landscape.
                    The concept of intelligence as something innate has been supplanted by the idea that
                    intelligence is not fixed, and that, with the right training, we can be the authors
                    of our own cognitive capabilities. Psychologist Alfred Binet, the developer of the
                    first intelligence tests, was one of many 19th-century scientists who held that
                    earlier view and sought to quantify cognitive ability. Then, in the early 20th
                    century, progressive thinkers revolted against the notion that inherent ability is
                    destiny. Instead, educators such as John Dewey argued that every child’s
                    intelligence could be developed, given the right environment.
                </p>
                <p>
                    ‘Growth mindset theory’ is a relatively new – and extremely popular – version of
                    this idea. In many schools today you will see hallways covered in motivational
                    posters and hear speeches on the mindset of great sporting heroes who simply
                    believed their way to the top. A major focus of the growth mindset in schools is
                    coaxing students away from seeing failure as an indication of their ability, and
                    towards seeing it as a chance to improve that ability. As educationalist Jeff Howard
                    noted several decades ago: ‘Smart is not something that you just are, smart is
                    something that you can get.’
                </p>
                <p>
                    The idea of the growth mindset is based on the work of psychologist Carol Dweck in
                    California in the 1990s. In one key experiment, Dweck divided a group of 10- to
                    12-year-olds into two groups. All were told that they had achieved a high score on a
                    test but the first group were praised for their intelligence in achieving this,
                    while the others were praised for their effort. The second group – those who had
                    been instilled with a ‘growth mindset’ – were subsequently far more likely to put
                    effort into future tasks. Meanwhile, the former took on only those tasks that would
                    not risk their sense of worth. This group had inferred that success or failure is
                    due to innate ability, and this ‘fixed mindset’ had led them to fear of failure and
                    lack of effort. Praising ability actually made the students perform worse, while
                    praising effort emphasised that change was possible.
                </p>
