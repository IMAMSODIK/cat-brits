                <p>When I started writing about Wegener’s life and work, one of the most intriguing
                    things about him for me was that, although he came up with a theory on continental
                    drift, he was not a geologist. He trained as an astronomer and pursued a career in
                    atmospheric physics. When he proposed the theory of continental displacements in
                    1912, he was a lecturer in physics and astronomy at the University of Marburg, in
                    southern Germany. However, he was not an ‘unknown’. In 1906 he had set a world
                    record (with his brother Kurt) for time aloft in a hot-air balloon: 52 hours.
                    Between 1906 and 1908 he had taken part in a highly publicized and extremely
                    dangerous expedition to the coast of northeast Greenland. He had also made a name
                    for himself amongst a small circle of meteorologists and atmospheric physicists in
                    Germany as the author of a textbook, Thermodynamics of the Atmosphere (1911), and of
                    a number of interesting scientific papers.</p>
