                <h3>The growth mindset</h3>
                <p>Over the past century, a powerful idea has taken root in the educational landscape.
                    The concept of intelligence as something innate has been supplanted by the idea that
                    intelligence is not fixed, and that, with the right training, we can be the authors
                    of our own cognitive capabilities. Psychologist Alfred Binet, the developer of the
                    first intelligence tests, was one of many 19th-century scientists who held that
                    earlier view and sought to quantify cognitive ability. Then, in the early 20th
                    century, progressive thinkers revolted against the notion that inherent ability is
                    destiny. Instead, educators such as John Dewey argued that every child’s
                    intelligence could be developed, given the right environment.</p>
                <p>‘Growth mindset theory’ is a relatively new – and extremely popular – version of this
                    idea. In many schools today you will see hallways covered in motivational posters
                    and hear speeches on the mindset of great sporting heroes who simply believed their
                    way to the top. A major focus of the growth mindset in schools is coaxing students
                    away from seeing failure as an indication of their ability, and towards seeing it as
                    a chance to improve that ability. As educationalist Jeff Howard noted several
                    decades ago: ‘Smart is not something that you just are, smart is something that you
                    can get.’</p>
                <p>The idea of the growth mindset is based on the work of psychologist Carol Dweck in
                    California in the 1990s. In one key experiment, Dweck divided a group of 10- to
                    12-year-olds into two groups. All were told that they had achieved a high score on a
                    test but the first group were praised for their intelligence in achieving this,
                    while the others were praised for their effort. The second group – those who had
                    been instilled with a ‘growth mindset’ – were subsequently far more likely to put
                    effort into future tasks. Meanwhile, the former took on only those tasks that would
                    not risk their sense of worth. This group had inferred that success or failure is
                    due to innate ability, and this ‘fixed mindset’ had led them to fear of failure and
                    lack of effort. Praising ability actually made the students perform worse, while
                    praising effort emphasised that change was possible.</p>
                <p>One of the greatest impediments to successfully implementing a growth mindset,
                    however, is the education system itself: in many parts of the world, the school
                    climate is obsessed with performance in the form of constant testing, analysing and
                    ranking of students – a key characteristic of the fixed mindset. Nor is it unusual
                    for schools to create a certain cognitive dissonance, when they applaud the benefits
                    of a growth mindset but then hand out fixed target grades in lessons based on
                    performance.</p>
                <p>Aside from the implementation problem, the original growth mindset research has also
                    received harsh criticism. The statistician Andrew Gelman claims that ‘their research
                    designs have enough degrees of freedom that they could take their data to support
                    just about any theory at all’. Professor of Psychology Timothy Bates, who has been
                    trying to replicate Dweck’s work, is finding that the results are repeatedly null.
                    He notes that: ‘People with a growth mindset don’t cope any better with failure …
                    Kids with the growth mindset aren’t getting better grades, either before or after
                    our intervention study.’</p>
                <p>Much of this criticism is not lost on Dweck, and she deserves great credit for
                    responding to it and adapting her work accordingly. In fact, she argues that her
                    work has been misunderstood and misapplied in a range of ways. She has also
                    expressed concerns that her theories are being misappropriated in schools by being
                    conflated with the self-esteem movement: ‘For me the growth mindset is a tool for
                    learning and improvement. It’s not just a vehicle for making children feel good.’
                </p>
                <p>But there is another factor at work here. The failure to translate the growth mindset
                    into the classroom might reflect a misunderstanding of the nature of teaching and
                    learning itself. Growth mindset supporters David Yeager and Gregory Walton claim
                    that interventions should be delivered in a subtle way to maximise their
                    effectiveness. They say that if adolescents perceive a teacher’s intervention as
                    conveying that they are in need of help, this could undo its intended effects.</p>
